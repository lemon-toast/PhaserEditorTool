import { expect, test } from '@playwright/test';

test('해상도·화면비와 배치 모드 전환·저장 복원·실행 취소', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: '예제 연출 열기' }).click();
  const modes = page.getByLabel('배치 모드', { exact: true });
  await expect(modes.locator('option')).toHaveCount(1);
  await page.locator('[data-node="money"]').click();
  const x = page.getByRole('spinbutton', { name: '위치 X', exact: true });
  await x.fill('42');
  await x.press('Tab');
  await page.getByLabel('화면 너비', { exact: true }).fill('1600');
  await page.getByLabel('화면비', { exact: true }).selectOption('16:9');
  await expect(page.getByLabel('화면 높이', { exact: true })).toHaveValue('900');
  await page.getByRole('button', { name: '해상도 적용', exact: true }).click();
  await expect(x).toHaveValue('42');
  await page.getByRole('button', { name: '모드 추가', exact: true }).click();
  await page.getByLabel('새 모드 이름', { exact: true }).fill('세로');
  await page.getByLabel('새 모드 너비', { exact: true }).fill('720');
  await page.getByLabel('새 모드 높이', { exact: true }).fill('1280');
  await page.getByRole('button', { name: '모드 만들기', exact: true }).click();
  await expect(modes).toHaveValue(/.+/);
  await page.getByLabel('화면 구성', { exact: true }).selectOption('responsive');
  await page.locator('[data-node="money"]').click();
  await expect(x).toHaveValue('42');
  await x.fill('321');
  await x.press('Tab');
  await modes.selectOption({ label: '가로' });
  await expect(page.getByLabel('화면 너비', { exact: true })).toHaveValue('1600');
  await page.locator('[data-node="money"]').click();
  await expect(x).toHaveValue('42');
  await modes.selectOption({ label: '세로' });
  await expect(page.getByLabel('화면 너비', { exact: true })).toHaveValue('720');
  await page.locator('[data-node="money"]').click();
  await expect(x).toHaveValue('321');
  await page.getByRole('button', { name: '↶ 실행 취소' }).click();
  await expect(modes.locator('option:checked')).toHaveText('가로');
  await page.getByRole('button', { name: '↷ 다시 실행' }).click();
  await expect(modes.locator('option:checked')).toHaveText('세로');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '작업 저장' }).click();
  const filePath = await (await download).path();
  await page.locator('input[type=file]').setInputFiles(filePath!);
  await expect(modes.locator('option')).toHaveCount(2);
  await expect(page.getByLabel('화면 구성', { exact: true })).toHaveValue('responsive');
  await modes.selectOption({ label: '가로' });
  await page.locator('[data-node="money"]').click();
  await expect(x).toHaveValue('42');
  await expect(page.getByLabel('화면 너비', { exact: true })).toHaveValue('1600');
  await page.screenshot({ path: 'test-results/layout-modes.png', fullPage: true });
  expect(errors).toEqual([]);
});

test('SlotClient 가로·세로 원본을 한 세트로 열고 원래 배치로 전환한다', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '프로젝트 SlotClient', exact: true }).click();
  await page.getByRole('button', { name: '선택한 화면 열기 →', exact: true }).click();
  const modes = page.getByLabel('배치 모드', { exact: true });
  await expect(modes.locator('option')).toHaveCount(2);
  await modes.selectOption({ label: '세로' });
  await expect(page.getByLabel('화면 너비', { exact: true })).toHaveValue('1080');
  await expect(page.getByLabel('화면 높이', { exact: true })).toHaveValue('1920');
  await expect(page.locator('[data-node="background"]')).toBeVisible();
  await modes.selectOption({ label: '가로' });
  await expect(page.getByLabel('화면 너비', { exact: true })).toHaveValue('1920');
  await expect(page.getByLabel('화면 높이', { exact: true })).toHaveValue('1080');
});
